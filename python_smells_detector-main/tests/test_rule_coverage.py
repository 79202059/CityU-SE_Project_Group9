"""Coverage fixtures for the seven rules no corpus ever triggered.

Four corpora (flask, requests, click and PyExamine itself) reach 40 of the
47 rules in ``rule_registry``.  The remaining seven are still shipped code,
so a rule that silently stops working would go unnoticed.  Each fixture
below is the smallest project that makes exactly one of those rules fire.

The fixtures are run through ``delta.analyze_tree`` rather than through a
single detector so that cross-file and architectural rules are exercised the
same way a real project would exercise them.
"""

import os
import shutil

import pytest

from code_quality_analyzer.config_handler import ConfigHandler
from code_quality_analyzer.delta import analyze_tree
from code_quality_analyzer.main import DEFAULT_CONFIG_NAME, resolve_config_path
from code_quality_analyzer.rule_registry import RULES_BY_ID, rule_id_for

HERE = os.path.dirname(os.path.abspath(__file__))
FIXTURES = os.path.join(HERE, "fixtures", "rule_coverage")
WORK = os.path.join(HERE, "_tmp_rule_coverage")

# rule id -> fixture directory that is expected to make it fire.
COVERAGE = (
    ("pyex-code-data-class", "data_class"),
    ("pyex-code-excessive-comments", "excessive_comments"),
    ("pyex-code-inappropriate-intimacy", "intimacy"),
    ("pyex-code-middle-man", "middle_man"),
    ("pyex-code-parallel-inheritance-hierarchies", "parallel_inheritance"),
    ("pyex-arch-potential-redundant-abstractions", "redundant_abstractions"),
)

FANOUT_RULE = "pyex-struct-high-fan-out"


@pytest.fixture(autouse=True)
def _clean_work():
    """The generated hub package is an artefact; leave no residue behind."""
    yield
    shutil.rmtree(WORK, ignore_errors=True)


def _handler():
    return ConfigHandler(resolve_config_path(DEFAULT_CONFIG_NAME))


def _rule_ids(directory):
    findings = analyze_tree(directory, _handler())
    return {rule_id_for(finding.smell_type, finding.category) for finding in findings}


def _write_hub(directory, count):
    """Write a hub module importing ``count`` local collaborators."""
    lines = ['"""Hub module generated by the coverage test."""', ""]
    for index in range(count):
        lines.append("import mod_%02d" % index)
    lines.extend(["", "", "def collect():"])
    lines.append("    return [")
    for index in range(count):
        lines.append("        mod_%02d.value()," % index)
    lines.append("    ]")
    path = os.path.join(directory, "hub.py")
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines) + "\n")


def _fanout_tree(count):
    """Build a throw-away package with ``count`` local modules behind a hub."""
    if os.path.isdir(WORK):
        shutil.rmtree(WORK, ignore_errors=True)
    os.makedirs(WORK)
    for index in range(count):
        path = os.path.join(WORK, "mod_%02d.py" % index)
        with open(path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write("def value():\n    return %d\n" % index)
    _write_hub(WORK, count)
    return WORK


def test_every_fixture_targets_a_registered_rule():
    targets = [rule_id for rule_id, _ in COVERAGE] + [FANOUT_RULE]
    for rule_id in targets:
        assert rule_id in RULES_BY_ID, rule_id


@pytest.mark.parametrize("rule_id,directory", COVERAGE)
def test_fixture_triggers_its_rule(rule_id, directory):
    found = _rule_ids(os.path.join(FIXTURES, directory))
    assert rule_id in found, "expected %s in %s" % (rule_id, sorted(found))


def test_fan_out_fixture_triggers_its_rule():
    found = _rule_ids(_fanout_tree(16))
    assert FANOUT_RULE in found, sorted(found)


def test_fan_out_stays_quiet_below_the_threshold():
    found = _rule_ids(_fanout_tree(15))
    assert FANOUT_RULE not in found, sorted(found)


def test_hub_fixture_matches_the_generated_shape():
    """The checked-in sample must stay equivalent to the generated hub."""
    sample = os.path.join(FIXTURES, "high_fanout", "hub.py")
    assert os.path.isfile(sample)
    generated = os.path.join(WORK, "hub.py")
    _fanout_tree(16)
    with open(sample, encoding="utf-8") as handle:
        sample_text = handle.read()
    with open(generated, encoding="utf-8") as handle:
        generated_text = handle.read()
    sample_imports = [line for line in sample_text.splitlines() if line.startswith("import ")]
    generated_imports = [
        line for line in generated_text.splitlines() if line.startswith("import ")
    ]
    assert sample_imports == generated_imports
